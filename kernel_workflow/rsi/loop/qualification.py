"""Fresh paired replay/online qualification and explicit KernelWiki publication."""

from dataclasses import asdict
from pathlib import Path

from kernelwiki import KnowledgeClient
from kernelwiki.knowledge import KnowledgeError, canonical
from kernelwiki.knowledge_store import KnowledgeUpdate

from ..evidence import read_json, reference, write_json
from ..harness import Policy
from ..replay_buffer.cohorts import cohorts
from ..replay_buffer.evaluate import evaluate, qualifies
from ..replay_buffer.objective import ReplayObjective, aggregate
from ..replay_buffer.store import open_buffer
from ..reverse_engineering.sources.capture import load_online
from .run import IncompleteStage, guard_inputs, read_completed


def qualify(root, initial, final, pool_manifest, settings):
    worlds, baseline_traces, candidate_traces, pairs = [], [], [], []
    final_ref = asdict(reference(root / "final/selected-policy.json"))
    frozen_at = read_json(root / "stages/final.done.json")["completed_at"]
    final_inputs = read_json(root / "stages/final.started.json")["inputs"]
    prior_worlds = open_buffer(final_inputs["rounds"][-1]["pool"]).worlds
    seen_worlds = {world.id for world in prior_worlds}
    seen_attempts = {node.attempt_id for world in prior_worlds for branch in world.branches for node in branch}
    for index, entry in enumerate(settings["entries"]["holdout"], 1):
        names = [f"holdout-{index}-incumbent", f"holdout-{index}-candidate"]
        results = []
        for name, policy in zip(names, (initial, final)):
            start = read_json(root / "stages" / (name + ".started.json"))
            if start["started_at"] < frozen_at or start["inputs"]["frozen_candidate"] != final_ref:
                raise KnowledgeError("fresh holdout must be collected after freezing the final candidate")
            result, world, _ = load_online(root / name)
            attempt_ids = {node.attempt_id for branch in world.branches for node in branch}
            if world.id in seen_worlds or attempt_ids & seen_attempts:
                raise KnowledgeError("previously inspected discoveries cannot serve as fresh holdout runs")
            seen_worlds.add(world.id)
            seen_attempts.update(attempt_ids)
            if read_json(root / name / "manifest.json")["config"] != entry["config"]:
                raise KnowledgeError("holdout used a different frozen generation configuration")
            if result["policy_revision"] != policy.revision or world.kernel != entry["config"]["kernel"]:
                raise KnowledgeError("holdout was not generated by its declared frozen policy and kernel")
            results.append((result, world))
        baseline, candidate = (item[0] for item in results)
        keys = ("root_source", "root_context", "reference_revision", "evaluator_protocol", "evaluator_runtime")
        if any(baseline[key] != candidate[key] for key in keys):
            raise KnowledgeError("paired online runs differ in original source, context, reference knowledge or evaluator")
        for key in ("kind", "node", "physical_gpus", "cpuset"):
            if baseline["execution"].get(key) != candidate["execution"].get(key):
                raise KnowledgeError("paired online runs differ in physical placement")
        for result, world in results:
            if (result["execution"]["kind"] != settings["kind"] or result["trace"]["budget"] != entry["config"]["budget"]
                    or result["trace"]["stop_reason"] not in {"policy_stop", "budget_exhausted"}
                    or any(node.measurement.status == "unknown" for branch in world.branches for node in branch)):
                raise KnowledgeError("incomplete or mixed-origin online pair cannot qualify")
        worlds.append(results[0][1])
        baseline_traces.append({**baseline["trace"], "world_id": f"paired/{index}"})
        candidate_traces.append({**candidate["trace"], "world_id": f"paired/{index}"})
        pairs.append({"kernel": entry["config"]["kernel"], "incumbent": asdict(reference(root / names[0] / "result.json")),
                      "candidate": asdict(reference(root / names[1] / "result.json"))})
    budgets = tuple(pool_manifest["budgets"])
    fixed_cohorts = cohorts(worlds, budgets)
    objective = ReplayObjective(**pool_manifest["objective"])
    baseline_replay = evaluate(worlds, initial, budgets, objective)
    candidate_replay = evaluate(worlds, final, budgets, objective)
    online_baseline = {"summary": aggregate(baseline_traces, objective), "traces": baseline_traces,
                       "qualification": {"eligible": all(trace["support_complete"] for trace in baseline_traces)}}
    online_candidate = {"summary": aggregate(candidate_traces, objective), "traces": candidate_traces,
                        "qualification": {"eligible": all(trace["support_complete"] for trace in candidate_traces)}}
    replay_pass = qualifies(candidate_replay, baseline_replay, held_out=True)
    online_pass = qualifies(online_candidate, online_baseline, held_out=True)
    return {"passed": replay_pass and online_pass, "replay_pass": replay_pass, "paired_online_pass": online_pass,
            "cohorts": fixed_cohorts, "incumbent_replay": baseline_replay, "candidate_replay": candidate_replay,
            "incumbent_online": online_baseline, "candidate_online": online_candidate, "pairs": pairs,
            "frozen_candidate": final_ref, "test_role": "new runs on the original test kernels, never returned to Developer",
            "limits": "paired online evidence is a release gate, not proof of reference-knowledge causality or general online improvement"}


def release(cycle_directory, wiki):
    root = Path(cycle_directory).resolve()
    result = read_completed(root)
    if result["status"] != "replay_validated" or result["execution_kind"] != "coordinated":
        raise KnowledgeError("only a real finally qualified cycle can publish; fixtures and inner rounds cannot")
    manifest = read_json(root / "manifest.json")
    if manifest["settings"]["kind"] != "coordinated" or manifest["approval"] is None:
        raise KnowledgeError("fixture or unapproved cycle cannot be relabeled as a real publication")
    guard_inputs(root, manifest, wiki)
    client = KnowledgeClient(wiki)
    records = client.snapshot().records
    initial = Policy.from_dict(read_json(root / "initial-policy.json"), records)
    candidate = Policy.from_dict(read_json(root / "final/selected-policy.json"), records)
    pool_manifest = open_buffer(manifest["settings"]["pool"]).manifest
    validation = qualify(root, initial, candidate, pool_manifest, manifest["settings"])
    if not validation["passed"] or canonical(validation) != canonical(read_json(root / "qualification/evidence.json")):
        raise KnowledgeError("final qualification no longer reproduces; publication aborted")
    evidence = (reference(root / "result.json"), reference(root / "qualification/evidence.json"))
    update = KnowledgeUpdate(candidate.knowledge, tuple(record for record in candidate.records if record.policy_rule),
                             {"status": "replay_validated", "policy_revision": candidate.revision,
                              "fresh_holdout": True, "paired_online_gate": True}, evidence)
    name = root / "release"
    if name.exists():
        raise IncompleteStage("release already started; inspect its receipt and KernelWiki pending/active state")
    write_json(name / "started.json", {"expected_revision": manifest["knowledge_revision"], "evidence": [asdict(item) for item in evidence]})
    revision = client.publish(update, expected_revision=manifest["knowledge_revision"])
    published = {"status": "replay_validated", "published": True, "revision": revision,
                 "previous_revision": manifest["knowledge_revision"]}
    write_json(name / "result.json", published)
    return published
